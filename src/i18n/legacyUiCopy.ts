export const legacyUiCopyPairs: LegacyUiCopyPair[] = [
  ...baseLegacyUiCopyPairs,
  ...supplementalUiCopyEntries.map((entry) => [entry.vi, entry.en] as const),
];


const flattenStrings = (value: unknown, prefix = "", output: Record<string, string> = {}): Record<string, string> => {
  if (!value || typeof value !== "object") return output;
  Object.entries(value as Record<string, unknown>).forEach(([key, entry]) => {
    const nextKey = prefix ? `${prefix}.${key}` : key;
    if (typeof entry === "string") output[nextKey] = entry;
    else flattenStrings(entry, nextKey, output);
  });
  return output;
};

const viFlat = flattenStrings(viTranslations);
const enFlat = flattenStrings(enTranslations);
const dictionary = new Map<string, { vi: string; en: string }>();

Object.keys(viFlat).forEach((key) => {
  const vi = viFlat[key];
  const en = enFlat[key];
  if (!en) return;
  dictionary.set(vi, { vi, en });
  dictionary.set(en, { vi, en });
});

baseLegacyUiCopyPairs.forEach(([vi, en]) => {
  dictionary.set(vi, { vi, en });
  dictionary.set(en, { vi, en });
});

supplementalUiCopyEntries.forEach(({ vi, en, sources = [] }) => {
  // Canonical dictionaries and the established compatibility memory retain
  // priority when a generic phrase is context-sensitive. Supplemental aliases
  // only fill uncovered literals discovered by the broader source audit.
  if (!dictionary.has(vi)) dictionary.set(vi, { vi, en });
  if (!dictionary.has(en)) dictionary.set(en, { vi, en });
  sources.forEach((source) => {
    if (!dictionary.has(source)) dictionary.set(source, { vi, en });
  });
});

const applyTemplate = (format: string, captures: readonly string[]): string =>
  format.replace(/\{\{(\d+)}}/g, (_match, index: string) => captures[Number(index) - 1] ?? "");

const resolveTemplateCopy = (source: string, locale: Locale): string | undefined => {
  const text = source.trim();
  for (const template of supplementalUiCopyTemplates) {
    const match = text.match(template.viPattern) ?? text.match(template.enPattern);
    if (!match) continue;
    return applyTemplate(template[locale], match.slice(1));
  }
  return undefined;
};

export function resolveLegacyUiCopy(source: string, locale: Locale): string {
  const exactMatch = dictionary.get(source.trim());
  const translated = exactMatch?.[locale] ?? resolveTemplateCopy(source, locale);
  if (!translated) return source;
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

export function hasLegacyUiCopy(source: string): boolean {
  if (dictionary.has(source.trim())) return true;
  return supplementalUiCopyTemplates.some((template) => template.viPattern.test(source.trim()) || template.enPattern.test(source.trim()));
}
